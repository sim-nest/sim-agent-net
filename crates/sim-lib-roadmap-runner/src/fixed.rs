//! Sealed fixed point over one generator per generated artifact.
//!
//! A seal binds the accepted source, the generated postimages, the proof
//! digest, and the facet identities. The first pass regenerates those
//! postimages and consults [`crate::proof_frontier`]. A later pass that still
//! carries that seal performs no generation and does not consult the frontier.
//! The seal is data. It does not apply a mutation plan or edit the revision.

use std::collections::{BTreeMap, BTreeSet};

use sim_artifact_facet::ArtifactFacet;
use sim_kernel::{ContentId, Datum, Symbol};
use thiserror::Error;

use crate::schedule::CLASS_PROOF_FAILED;
use crate::{ProofOutcome, Revision, image_id, proof_frontier};

#[path = "fixed_check.rs"]
mod check;

pub use check::FactGenerator;

/// Why sealing could not form an identity.
#[derive(Debug, Error, PartialEq, Eq)]
pub enum FixedError {
    /// A content id could not be formed.
    #[error("identity: {0}")]
    Identity(String),
    /// The proof frontier refused its inputs.
    #[error("proof frontier: {0}")]
    Frontier(String),
}

/// Identity of one sealed fixed point.
///
/// The id covers the source seal, the accepted image, the proof digest, the
/// facet digest, and each generated path with its accepted bytes.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FixedSeal {
    /// Content id of this closure.
    pub id: ContentId,
    /// Accepted image id.
    pub image: ContentId,
    /// Content id of the accepted source-seal bytes.
    pub source: ContentId,
    /// Digest of each claim's proof outcome.
    pub proof: ContentId,
    /// Digest of the facet identities.
    pub facets: ContentId,
}

/// Result of judging one fixed point. The revision is never edited.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FixedStep {
    /// Generated bytes, proofs, source, and ownership agree.
    Sealed {
        /// Closure identity.
        seal: FixedSeal,
        /// Number of generator calls on this pass.
        work: u32,
    },
    /// The supplied seal still matches. No generator ran.
    ZeroWork {
        /// The same closure identity.
        seal: FixedSeal,
    },
    /// The seal is refused. `repeated` is set only for an oscillation witness.
    Blocked {
        /// Stable reason.
        reason: &'static str,
        /// Paths or claim ids named by the refusal.
        closure: BTreeSet<String>,
        /// Image id that repeated, when `reason` is `oscillation`.
        repeated: Option<ContentId>,
    },
    /// A deleted generated path names its generator closure. Nothing is written.
    Invalidated {
        /// That generator's write set and the claims that read it.
        closure: BTreeSet<String>,
        /// Write paths of generators the deletion does not name.
        retained: BTreeSet<String>,
    },
    /// The retained generator reproduced the accepted bytes.
    Retired {
        /// Generator calls. This is one.
        work: u32,
    },
}

/// Bind source, generated postimages, proof, and ownership.
///
/// `deleted` reports the generator closure instead of sealing. `prior` is the
/// seal returned by an earlier pass; when it still matches, this call performs
/// no generation. Contract refusals are [`FixedStep`] values.
pub fn seal_fixed_point(
    revision: &Revision,
    facets: &[ArtifactFacet],
    generators: &[&dyn FactGenerator],
    proofs: &BTreeMap<String, ProofOutcome>,
    deleted: &BTreeSet<String>,
    prior: Option<&FixedSeal>,
) -> Result<FixedStep, FixedError> {
    if revision.is_uncertain() {
        return Ok(blocked("uncertain", BTreeSet::new()));
    }
    let open = open_claims(revision);
    if !open.is_empty() {
        return Ok(blocked("open-claim", open));
    }
    if !deleted.is_empty() {
        let checked = match check::check(revision, facets, generators) {
            Ok(checked) => checked,
            Err(refusal) => return Ok(refuse(refusal)),
        };
        return Ok(check::invalidate(revision, &checked, deleted));
    }
    if let Some(prior) = prior
        && let Some(seal) = matching_seal(revision, facets, proofs, prior)?
    {
        return Ok(FixedStep::ZeroWork { seal });
    }
    let checked = match check::check(revision, facets, generators) {
        Ok(checked) => checked,
        Err(refusal) => return Ok(refuse(refusal)),
    };
    let proof = match judge_proofs(revision, proofs)? {
        Ok(proof) => proof,
        Err(refusal) => return Ok(refuse(refusal)),
    };
    let facets_id = facet_digest(facets)?;
    let (produced, work) = match generate(revision, generators) {
        Ok(produced) => produced,
        Err(refusal) => return Ok(refuse(refusal)),
    };
    let produced_paths: BTreeSet<String> = produced.keys().cloned().collect();
    let owned_paths: BTreeSet<String> = checked.generated.keys().cloned().collect();
    if produced_paths != owned_paths {
        return Ok(blocked(
            "split-generator",
            symdiff(&produced_paths, &owned_paths),
        ));
    }
    let accepted_image = image(revision.images())?;
    let delta = changed(&produced, revision);
    if delta.is_empty() {
        let id = bind_seal(
            &revision.seal,
            &accepted_image,
            &proof,
            &facets_id,
            &produced,
        )?;
        return Ok(FixedStep::Sealed {
            seal: FixedSeal {
                id,
                image: accepted_image,
                source: revision.seal.clone(),
                proof,
                facets: facets_id,
            },
            work,
        });
    }
    let candidate_bytes = candidate(revision, &produced);
    let candidate_id = image(&candidate_bytes)?;
    if revision.has_seen(&candidate_id) {
        return Ok(FixedStep::Blocked {
            reason: "oscillation",
            closure: delta,
            repeated: Some(candidate_id),
        });
    }
    Ok(blocked("gap", delta))
}

/// Retire `duplicate` after `retained` reproduces the accepted write set.
///
/// The duplicate is not run. A differing write set or a differing byte string
/// refuses, and the revision is left unchanged.
pub fn retire_duplicate(
    revision: &Revision,
    retained: &dyn FactGenerator,
    duplicate: &dyn FactGenerator,
) -> Result<FixedStep, FixedError> {
    if retained.writes() != duplicate.writes() {
        return Ok(blocked(
            "different-closure",
            symdiff(retained.writes(), duplicate.writes()),
        ));
    }
    if retained.writes().is_empty() {
        return Ok(blocked("split-generator", BTreeSet::new()));
    }
    let cycles: BTreeSet<String> = retained
        .reads()
        .intersection(retained.writes())
        .cloned()
        .collect();
    if !cycles.is_empty() {
        return Ok(blocked("generator-cycle", cycles));
    }
    let source = match source_of(revision, retained) {
        Ok(source) => source,
        Err(refusal) => return Ok(refuse(refusal)),
    };
    let output = retained.generate(&source);
    let keys: BTreeSet<String> = output.keys().cloned().collect();
    if &keys != retained.writes() {
        return Ok(blocked("not-zero", symdiff(&keys, retained.writes())));
    }
    let delta = changed(&output, revision);
    if !delta.is_empty() {
        return Ok(blocked("not-zero", delta));
    }
    Ok(FixedStep::Retired { work: 1 })
}

fn matching_seal(
    revision: &Revision,
    facets: &[ArtifactFacet],
    proofs: &BTreeMap<String, ProofOutcome>,
    prior: &FixedSeal,
) -> Result<Option<FixedSeal>, FixedError> {
    let image = image(revision.images())?;
    let proof = proof_digest(revision, proofs)?;
    let facets_id = facet_digest(facets)?;
    if prior.image != image
        || prior.source != revision.seal
        || prior.proof != proof
        || prior.facets != facets_id
    {
        return Ok(None);
    }
    let Some(generated) = accepted_generated(revision, facets) else {
        return Ok(None);
    };
    let id = bind_seal(&revision.seal, &image, &proof, &facets_id, &generated)?;
    if prior.id != id {
        return Ok(None);
    }
    Ok(Some(prior.clone()))
}

fn judge_proofs(
    revision: &Revision,
    proofs: &BTreeMap<String, ProofOutcome>,
) -> Result<Result<ContentId, Refusal>, FixedError> {
    let claims: Vec<String> = revision.claims().keys().cloned().collect();
    let relevant = claims
        .iter()
        .filter_map(|id| proofs.get(id).map(|outcome| (id.clone(), *outcome)))
        .collect::<BTreeMap<_, _>>();
    let frontier = proof_frontier(&claims, &relevant)
        .map_err(|error| FixedError::Frontier(error.to_string()))?;
    if !frontier.failures.is_empty() || frontier.continuation.is_some() {
        let mut closure = frontier
            .failures
            .iter()
            .map(|failure| failure.unit.clone())
            .collect::<BTreeSet<_>>();
        if let Some(continuation) = frontier.continuation {
            closure.extend(continuation.remaining);
        }
        let reason = if frontier.failures.is_empty() {
            "proof-gap"
        } else {
            CLASS_PROOF_FAILED
        };
        return Ok(Err(refusal(reason, closure)));
    }
    proof_digest(revision, proofs).map(Ok)
}

fn generate(
    revision: &Revision,
    generators: &[&dyn FactGenerator],
) -> Result<(BTreeMap<String, Vec<u8>>, u32), Refusal> {
    let missing = check::absent_writes(revision, generators);
    if !missing.is_empty() {
        return Err(refusal("unknown-fact", missing));
    }
    let mut produced = BTreeMap::new();
    let mut work = 0u32;
    for generator in generators {
        let source = source_of(revision, *generator)?;
        let output = generator.generate(&source);
        work = work.saturating_add(1);
        let keys: BTreeSet<String> = output.keys().cloned().collect();
        if &keys != generator.writes() {
            return Err(refusal("gap", symdiff(&keys, generator.writes())));
        }
        produced.extend(output);
    }
    Ok((produced, work))
}

fn source_of(
    revision: &Revision,
    generator: &dyn FactGenerator,
) -> Result<BTreeMap<String, Vec<u8>>, Refusal> {
    let mut source = BTreeMap::new();
    let mut missing = BTreeSet::new();
    for path in generator.reads() {
        match revision.images().get(path) {
            Some(bytes) => {
                source.insert(path.clone(), bytes.clone());
            }
            None => {
                missing.insert(path.clone());
            }
        }
    }
    if missing.is_empty() {
        Ok(source)
    } else {
        Err(refusal("unknown-fact", missing))
    }
}

fn accepted_generated(
    revision: &Revision,
    facets: &[ArtifactFacet],
) -> Option<BTreeMap<String, Vec<u8>>> {
    let mut generated = BTreeMap::new();
    for facet in facets {
        let sim_artifact_facet::RegionSelector::ExactPath(path) = facet.region() else {
            return None;
        };
        let sim_artifact_facet::RegionOwnership::Generated { .. } = facet.ownership() else {
            continue;
        };
        generated.insert(path.clone(), revision.images().get(path)?.clone());
    }
    Some(generated)
}

fn changed(produced: &BTreeMap<String, Vec<u8>>, revision: &Revision) -> BTreeSet<String> {
    produced
        .iter()
        .filter(|(path, bytes)| revision.images().get(*path) != Some(*bytes))
        .map(|(path, _)| path.clone())
        .collect()
}

fn candidate(
    revision: &Revision,
    produced: &BTreeMap<String, Vec<u8>>,
) -> BTreeMap<String, Vec<u8>> {
    let mut image = revision.images().clone();
    for (path, bytes) in produced {
        image.insert(path.clone(), bytes.clone());
    }
    image
}

fn open_claims(revision: &Revision) -> BTreeSet<String> {
    revision
        .claims()
        .iter()
        .filter(|(_, claim)| !claim.closed)
        .map(|(id, _)| id.clone())
        .collect()
}

fn proof_digest(
    revision: &Revision,
    proofs: &BTreeMap<String, ProofOutcome>,
) -> Result<ContentId, FixedError> {
    let votes = revision
        .claims()
        .keys()
        .map(|id| {
            let outcome = match proofs.get(id) {
                Some(ProofOutcome::Passed) => "passed",
                Some(ProofOutcome::Failed) => "failed",
                None => "absent",
            };
            Datum::Node {
                tag: Symbol::qualified("roadmap-runner", "ProofVoteV1"),
                fields: vec![
                    (Symbol::new("claim"), Datum::String(id.clone())),
                    (Symbol::new("outcome"), Datum::String(outcome.to_owned())),
                ],
            }
        })
        .collect();
    node("ProofDigestV1", Datum::List(votes))
}

fn facet_digest(facets: &[ArtifactFacet]) -> Result<ContentId, FixedError> {
    let mut ids: Vec<&ContentId> = facets.iter().map(|facet| facet.id().content_id()).collect();
    ids.sort();
    node(
        "FacetDigestV1",
        Datum::List(ids.into_iter().map(id_datum).collect()),
    )
}

fn bind_seal(
    source: &ContentId,
    image: &ContentId,
    proof: &ContentId,
    facets: &ContentId,
    generated: &BTreeMap<String, Vec<u8>>,
) -> Result<ContentId, FixedError> {
    let mut list = vec![
        id_datum(source),
        id_datum(image),
        id_datum(proof),
        id_datum(facets),
    ];
    for (path, bytes) in generated {
        list.push(Datum::Node {
            tag: Symbol::qualified("roadmap-runner", "GeneratedFactV1"),
            fields: vec![
                (Symbol::new("path"), Datum::String(path.clone())),
                (Symbol::new("bytes"), Datum::Bytes(bytes.clone())),
            ],
        });
    }
    node("FixedPointV1", Datum::List(list))
}

fn image(images: &BTreeMap<String, Vec<u8>>) -> Result<ContentId, FixedError> {
    image_id(images).map_err(|error| FixedError::Identity(error.to_string()))
}

fn id_datum(id: &ContentId) -> Datum {
    Datum::Node {
        tag: Symbol::qualified("core", "ContentId"),
        fields: vec![
            (
                Symbol::new("algorithm"),
                Datum::Symbol(id.algorithm.clone()),
            ),
            (Symbol::new("bytes"), Datum::Bytes(id.bytes.to_vec())),
        ],
    }
}

fn node(name: &str, payload: Datum) -> Result<ContentId, FixedError> {
    Datum::Node {
        tag: Symbol::qualified("roadmap-runner", name),
        fields: vec![(Symbol::new("payload"), payload)],
    }
    .content_id()
    .map_err(|error| FixedError::Identity(error.to_string()))
}

fn symdiff(left: &BTreeSet<String>, right: &BTreeSet<String>) -> BTreeSet<String> {
    left.symmetric_difference(right).cloned().collect()
}

pub(super) struct Refusal {
    reason: &'static str,
    closure: BTreeSet<String>,
}

pub(super) fn refusal(reason: &'static str, closure: BTreeSet<String>) -> Refusal {
    Refusal { reason, closure }
}

fn refuse(refusal: Refusal) -> FixedStep {
    blocked(refusal.reason, refusal.closure)
}

pub(super) fn blocked(reason: &'static str, closure: BTreeSet<String>) -> FixedStep {
    FixedStep::Blocked {
        reason,
        closure,
        repeated: None,
    }
}

